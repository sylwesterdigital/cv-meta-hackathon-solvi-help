import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import {namedRoomFurnishingInstruction,roomFurnishingSequence,nextRoomFurnishing} from '../js/robot-room-furnishing.js';
import {localProjectSequence,workRecoveryPlan} from '../js/robot-autonomy-policy.js';
import {cleanAutonomyDecision} from '../js/robot-autonomy-core.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const source=p=>readFileSync(resolve(root,p),'utf8');
test('Direct instructions from the human become a bounded room-furnishing sequence',()=>{
 const sample='@Ania but what about adding a fridge and telly to this room you are just in?';
 assert.equal(namedRoomFurnishingInstruction(sample,'Ania'),sample);
 assert.deepEqual(roomFurnishingSequence(sample),['fridge','tv']);
 assert.deepEqual(localProjectSequence(sample),['fridge','tv']);
 assert.ok(namedRoomFurnishingInstruction('@Ania please add a fridge and television here','Ania'));
 assert.ok(namedRoomFurnishingInstruction('@Ania can you place a TV and a lamp in this room','Ania'));
 assert.equal(namedRoomFurnishingInstruction('@Ania I love the idea of fridge and TV','Ania'),null);
 assert.equal(namedRoomFurnishingInstruction('@Choka add fridge and TV','Ania'),null);
 assert.deepEqual(roomFurnishingSequence('@Ania do not add the fridge to this room'),[]);
 assert.deepEqual(roomFurnishingSequence('@Ania please add a fridge, fridge and 2 TVs'),['fridge','tv']);
});
test('A failed item is deferred, another is attempted, and the original ID can later resume',()=>{
 const sequence=['fridge','tv'];
 const now=Date.now(),skip=[{variant:'fridge',attempts:1,retryAt:now+10000,reason:'occupied'}];
 assert.equal(nextRoomFurnishing(sequence,[],skip,now).variant,'tv');
 assert.equal(nextRoomFurnishing(sequence,[{id:'tv1',variant:'tv'}],skip,now).variant,null);
 assert.equal(nextRoomFurnishing(sequence,[{id:'tv1',variant:'tv'}],skip,now).nextRetryAt,now+10000);
 assert.equal(nextRoomFurnishing(sequence,[{id:'tv1',variant:'tv'}],skip,now+10001).variant,'fridge');
 assert.equal(nextRoomFurnishing(sequence,[{id:'tv1',variant:'tv'},{id:'fridge1',variant:'fridge'}],skip,now).done,true);
 assert.equal(nextRoomFurnishing(sequence,[{variant:'tv'}],[],now).done,false);
});
test('Meta-free recovery selects real furnishing tool and reports completion only with receipts',()=>{
 const goal='@Ania add a fridge and telly to this room';
 assert.equal(workRecoveryPlan({goal,allowChanges:true}).action,'furnish_room');
 assert.equal(workRecoveryPlan({goal,allowChanges:true}).variant,'fridge');
 assert.equal(workRecoveryPlan({goal,allowChanges:true,projectPlaced:[{id:'f1',variant:'fridge'}]}).variant,'tv');
 assert.match(workRecoveryPlan({goal,allowChanges:true,projectPlaced:[{id:'f1',variant:'fridge'},{id:'t1',variant:'tv'}]}).reason,/GOAL REACHED/);
 assert.equal(workRecoveryPlan({goal:'Build one house with a fridge and a TV',allowChanges:true}).action,'build_house');
 assert.equal(cleanAutonomyDecision({action:'furnish_room',variant:'make_nuclear_reactor'},[],'bot'),null);
 assert.equal(cleanAutonomyDecision({action:'furnish_room',variant:'tv'},[],'bot')?.variant,'tv');
});
